-- Инициализация базы данных hydrogen_pinch
-- Создание таблицы потоков и заполнение начальными данными

CREATE TABLE IF NOT EXISTS streams (
    id              INTEGER PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    type            VARCHAR(10)  NOT NULL CHECK (type IN ('Source', 'Sink')),
    flow_rate       DOUBLE PRECISION NOT NULL CHECK (flow_rate > 0),
    purity          DOUBLE PRECISION NOT NULL CHECK (purity >= 0 AND purity <= 100),
    allowed_connections INTEGER[] DEFAULT '{}'
);

